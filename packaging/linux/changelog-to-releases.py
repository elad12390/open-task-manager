#!/usr/bin/env python3
"""Write the <releases> entries of the MetaInfo file from CHANGELOG.md.

Each released version (a changelog section with a v<version> tag) becomes one <release>, dated by its tag.
Sections without a tag are unreleased and are left out. Only the text between the two markers in the
MetaInfo file is rewritten.

Usage: uv run packaging/linux/changelog-to-releases.py [--check]
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path
from xml.etree import ElementTree
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
CHANGELOG = ROOT / "CHANGELOG.md"
METAINFO = ROOT / "packaging/linux/io.github.elad12390.OpenTaskManager.metainfo.xml"
BEGIN = "<!-- BEGIN RELEASES (generated by packaging/linux/changelog-to-releases.py) -->"
END = "<!-- END RELEASES -->"
HEADING = re.compile(r"^## \[(\d+\.\d+\.\d+)\]")


def sections(text):
    found, current = [], None
    for line in text.splitlines():
        match = HEADING.match(line)
        if match:
            current = (match.group(1), [])
            found.append(current)
        elif line.startswith("## "):
            current = None
        elif current is not None:
            current[1].append(line)
    return found


def blocks_of(lines):
    """Paragraphs and list items; wrapped lines join the item or paragraph they continue."""
    blocks = []
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        if raw.startswith("- "):
            blocks.append(["li", line[2:]])
        elif raw.startswith("  ") and blocks and blocks[-1][0] == "li":
            blocks[-1][1] += " " + line
        elif blocks and blocks[-1][0] == "p":
            blocks[-1][1] += " " + line
        else:
            blocks.append(["p", line])
    return blocks


def description(blocks):
    xml, in_list = [], False
    for tag, text in blocks:
        if tag == "li" and not in_list:
            xml.append("<ul>")
            in_list = True
        elif tag == "p" and in_list:
            xml.append("</ul>")
            in_list = False
        xml.append(f"<li>{escape(text)}</li>" if tag == "li" else f"<p>{escape(text)}</p>")
    if in_list:
        xml.append("</ul>")
    return xml


def tag_date(version):
    result = subprocess.run(
        ["git", "-C", str(ROOT), "log", "-1", "--format=%cs", f"v{version}"],
        capture_output=True,
        text=True,
    )
    return result.stdout.strip() if result.returncode == 0 else ""


def releases_block():
    lines = []
    for version, body in sections(CHANGELOG.read_text(encoding="utf-8")):
        date = tag_date(version)
        blocks = blocks_of(body)
        if not date or not blocks:
            continue
        lines.append(f'    <release version="{version}" date="{date}">')
        lines.append("      <description>")
        lines.extend("        " + part for part in description(blocks))
        lines.append("      </description>")
        lines.append("    </release>")
    return "\n".join(lines)


def rewrite(text, block):
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"{METAINFO.name}: the BEGIN/END RELEASES markers are missing")
    updated = pattern.sub(lambda _: f"{BEGIN}\n{block}\n    {END}", text, count=1)
    ElementTree.fromstring(updated)
    return updated


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing when out of date")
    args = parser.parse_args()
    current = METAINFO.read_text(encoding="utf-8")
    updated = rewrite(current, releases_block())
    if updated == current:
        print("releases are up to date")
        return 0
    if args.check:
        print("releases are out of date: run packaging/linux/changelog-to-releases.py", file=sys.stderr)
        return 1
    METAINFO.write_text(updated, encoding="utf-8")
    print(f"wrote releases to {METAINFO.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
